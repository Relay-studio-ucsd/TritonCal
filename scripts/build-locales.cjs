// 将标准语言包转换为本地脚本，供插件即时切换；不向 TSS 或外网请求翻译。
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "../extension");
function buildLocales() {
  const catalogs = {};
  for (const language of ["en", "zh_CN"]) {
    const source = JSON.parse(fs.readFileSync(path.join(root, "_locales", language, "messages.json"), "utf8"));
    catalogs[language] = Object.fromEntries(Object.entries(source).map(([key, entry]) => [key,
      entry.message.replace(/\$([a-z0-9_]+)\$/gi, (_, name) => entry.placeholders[name.toLowerCase()].content)
    ]));
  }
  return `// Generated by scripts/build-locales.cjs; edit _locales/*/messages.json instead.\nglobalThis.TritonCalMessages = ${JSON.stringify(catalogs, null, 2)};\n`;
}
if (require.main === module) fs.writeFileSync(path.join(root, "locales.js"), buildLocales());
module.exports = { buildLocales };
